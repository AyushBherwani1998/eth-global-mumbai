// Regenerates src/abis.generated.ts from the committed frontend ABIs in contracts/abis (`make abis`), so viem gets
// `as const` types without a second copy to maintain by hand.
//   node scripts/gen-abis.ts           write the file
//   node scripts/gen-abis.ts --check   exit 1 if it is out of date (CI)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const abisDir = join(here, "../../../contracts/abis");
const out = join(here, "../src/abis.generated.ts");

const SOURCES: Record<string, string> = {
  ccaAbi: "IContinuousClearingAuction",
  listingHookAbi: "IListingHook",
  receiverAbi: "IListingPolicyReceiver",
  allowAllModuleAbi: "AllowAllModule",
  validationHookAbi: "AuctionValidationHook",
  eligibilityModuleAbi: "IEligibilityModule",
  permit2Abi: "IAllowanceTransfer",
  stateViewAbi: "IStateView",
  quoterAbi: "IV4Quoter",
  poolManagerAbi: "IPoolManager",
  erc20Abi: "IERC20Metadata",
  mockSmeAbi: "MockSME",
  lbpStrategyAbi: "ILBPStrategy",
};

function render(): string {
  const lines = [
    "// Generated by scripts/gen-abis.ts from contracts/abis/*.json. Do not edit; run `npm run abis`.",
    "/* eslint-disable */",
    "",
  ];
  for (const [name, file] of Object.entries(SOURCES)) {
    const abi = JSON.parse(readFileSync(join(abisDir, `${file}.json`), "utf8")) as unknown[];
    lines.push(`/** contracts/abis/${file}.json */`);
    lines.push(`export const ${name} = [`);
    for (const item of abi) lines.push(`  ${JSON.stringify(item)},`);
    lines.push("] as const;", "");
  }
  return lines.join("\n");
}

const next = render();
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(out, "utf8");
  } catch {
    // missing counts as stale
  }
  if (current !== next) {
    console.error("src/abis.generated.ts is out of date with contracts/abis: run `npm run abis` and commit it");
    process.exit(1);
  }
  console.log("src/abis.generated.ts is current");
} else {
  writeFileSync(out, next);
  console.log(`wrote ${out}`);
}
